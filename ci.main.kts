#!/usr/bin/env kotlin
// Generates .github/workflows/ci.yml. Run: `kotlin ci.main.kts`. Never edit the YAML by hand.
// Plain Kotlin script with no dependencies (no new deps without approval, see AGENTS.md).

import java.io.File

data class Step(val name: String, val uses: String? = null, val run: String? = null, val with: Map<String, String> = emptyMap())

data class Job(val id: String, val name: String, val runsOn: String, val steps: List<Step>)

fun yaml(name: String, jobs: List<Job>): String = buildString {
    appendLine("# Generated by ci.main.kts. Do not edit; run `kotlin ci.main.kts`.")
    appendLine("name: $name")
    appendLine("on:")
    appendLine("  push:")
    appendLine("    branches: [main]")
    appendLine("  pull_request:")
    appendLine("permissions:")
    appendLine("  contents: read")
    appendLine("jobs:")
    for (job in jobs) {
        appendLine("  ${job.id}:")
        appendLine("    name: ${job.name}")
        appendLine("    runs-on: ${job.runsOn}")
        appendLine("    timeout-minutes: 30")
        appendLine("    steps:")
        for (step in job.steps) {
            appendLine("      - name: ${step.name}")
            step.uses?.let { appendLine("        uses: $it") }
            if (step.with.isNotEmpty()) {
                appendLine("        with:")
                step.with.forEach { (k, v) -> appendLine("          $k: $v") }
            }
            step.run?.let { appendLine("        run: $it") }
        }
    }
}

val checkout = Step("Checkout", uses = "actions/checkout@v4")
val java = Step("Set up JDK 21", uses = "actions/setup-java@v4", with = mapOf("distribution" to "temurin", "java-version" to "21"))
val gradle = Step("Set up Gradle", uses = "gradle/actions/setup-gradle@v4")

// `build` also bundles the wasmJs app into the CLI jar, so one job covers the web build too.
val jobs = listOf(
    Job(
        "build", "Build and test", "ubuntu-latest",
        listOf(
            checkout, java, gradle,
            Step("Build and test", run = "./gradlew build :cli:installDist --console=plain"),
            Step("Web app is packaged", run = "unzip -l cli/build/libs/cli-*.jar | grep -q 'web/index.html'"),
        ),
    ),
)

val out = File(".github/workflows/ci.yml")
out.parentFile.mkdirs()
out.writeText(yaml("CI", jobs))
println("Wrote ${out.path}")
